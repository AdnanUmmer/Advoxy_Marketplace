"""Build static/css/app.css with the Tailwind standalone CLI (no Node needed).

The pytailwindcss package downloads the pinned Tailwind binary on first use.

Class names are collected from templates and Python files by this command and
handed to Tailwind through `@source inline(...)` (static/src/_candidates.css).
This avoids Tailwind's file scanner, which silently finds nothing on some
Windows setups, and gives identical output on every OS.
"""

import re
import subprocess

from django.conf import settings
from django.core.management.base import BaseCommand

TAILWIND_VERSION = "v4.3.4"
SCAN_GLOBS = [("templates", "**/*.html"), ("apps", "**/*.html"), ("apps", "**/*.py"), ("static/js", "**/*.js")]
QUOTED = re.compile(r"\"([^\"\n]*)\"|'([^'\n]*)'")
SAFE_TOKEN = re.compile(r"^[A-Za-z0-9_:/\[\]().#!@*&>+~=,%\-]+$")
# Django tags/variables are replaced by spaces first, so a class written right
# next to one (e.g. `lg:grid{% endif %}`) is still collected.
TEMPLATE_TAG = re.compile(r"{%.*?%}|{{.*?}}|{#.*?#}", re.S)


def _balanced(token):
    depth = {"(": 0, "[": 0}
    for ch in token:
        if ch in "([":
            depth[ch] += 1
        elif ch == ")":
            depth["("] -= 1
        elif ch == "]":
            depth["["] -= 1
        if min(depth.values()) < 0:
            return False
    return not any(depth.values()) and not token.endswith((",", "."))


def collect_candidates(base_dir):
    tokens = set()
    for folder, pattern in SCAN_GLOBS:
        for path in (base_dir / folder).glob(pattern):
            text = path.read_text(encoding="utf-8", errors="ignore")
            if path.suffix == ".html":
                text = TEMPLATE_TAG.sub(" ", text)
            for match in QUOTED.finditer(text):
                for token in (match.group(1) or match.group(2) or "").split():
                    # Alpine/JS expressions nest quotes: :class="x ? 'block h-4' : 'hidden'"
                    token = token.strip("'\"`,;")
                    if not token:
                        continue
                    starts_ok = token[0].isalpha() or token[0] in "-!@"
                    if SAFE_TOKEN.match(token) and starts_ok and _balanced(token):
                        tokens.add(token)
    return sorted(tokens)


class Command(BaseCommand):
    help = "Compile Tailwind CSS (static/src/app.css -> static/css/app.css)."

    def add_arguments(self, parser):
        parser.add_argument("--watch", action="store_true", help="Rebuild on CSS changes (re-run after template edits).")

    def handle(self, *args, **opts):
        from pytailwindcss import get_bin_path, install

        base = settings.BASE_DIR
        candidates = collect_candidates(base)
        (base / "static" / "src" / "_candidates.css").write_text(
            "/* Generated by `manage.py build_css`. Do not edit. */\n"
            f'@source inline("{" ".join(candidates)}");\n',
            encoding="utf-8",
        )

        bin_path = get_bin_path(version=TAILWIND_VERSION)
        if not bin_path.exists():
            self.stdout.write(f"Downloading Tailwind CLI {TAILWIND_VERSION}...")
            install(bin_path=bin_path, version=TAILWIND_VERSION)
        src = base / "static" / "src" / "app.css"
        out = base / "static" / "css" / "app.css"
        cmd = [str(bin_path), "-i", str(src), "-o", str(out)]
        cmd.append("--watch" if opts["watch"] else "--minify")
        subprocess.run(cmd, check=True, cwd=base)
        self.stdout.write(self.style.SUCCESS(f"Built {out.relative_to(base)} ({len(candidates)} candidates)"))
